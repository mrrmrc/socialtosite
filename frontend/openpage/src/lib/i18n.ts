export function t(source: string): string {
  const dictionary = getBrowserLanguage() === 'it' ? italian : english
  if (dictionary[source]) return dictionary[source]
  for (const prefix of ['Duplicate ', 'Remove ', 'Drag to reorder ']) {
    if (source.startsWith(prefix)) {
      const label = prefix === 'Drag to reorder ' ? (getBrowserLanguage() === 'it' ? 'Trascina per riordinare ' : prefix) : t(prefix.trim()) + ' '
      return label + t(source.slice(prefix.length))
    }
  }
  return source
}
