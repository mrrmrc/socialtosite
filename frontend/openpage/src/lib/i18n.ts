// Translate builder controls only. The customer's website content is never translated.
export type BrowserLanguage = 'it' | 'en'
export function getBrowserLanguage(languages?: readonly string[]): BrowserLanguage {
  const preferred = languages ?? (typeof navigator === 'undefined' ? ['en'] : navigator.languages?.length ? navigator.languages : [navigator.language])
  return preferred[0]?.toLowerCase().startsWith('it') ? 'it' : 'en'
}
